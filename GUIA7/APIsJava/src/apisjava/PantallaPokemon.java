    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String entrada = txtBusqueda.getText().toLowerCase().trim();
    String filtro = cmbFiltro.getSelectedItem().toString(); // "Nombre" o "Tipo"
    
    // Limpiamos los campos antes de una nueva búsqueda
    lblNombre.setText("Cargando...");
    lblImagen.setIcon(null);
    lblStats.setText("");
    
    try {
        CloseableHttpClient httpClient = HttpClients.createDefault();
        
        // DECIDIR LA URL SEGÚN EL COMBOBOX
        String url;
        if (filtro.equals("Nombre")) {
            url = "https://pokeapi.co/api/v2/pokemon/" + entrada;
        } else {
            url = "https://pokeapi.co/api/v2/type/" + entrada;
        }

        HttpGet request = new HttpGet(url);
        CloseableHttpResponse response = httpClient.execute(request);
        
        if (response.getStatusLine().getStatusCode() == 200) {
            String json = EntityUtils.toString(response.getEntity());
            JsonObject objetoJson = new Gson().fromJson(json, JsonObject.class);

            if (filtro.equals("Nombre")) {
                // SI ES NOMBRE: Mostramos los detalles directamente
                actualizarDetalles(objetoJson);
            } else {
                // SI ES TIPO: Llenamos la lista central con nombres
                DefaultListModel modelo = new DefaultListModel();
                JsonArray lista = objetoJson.getAsJsonArray("pokemon");
                for (int i = 0; i < lista.size(); i++) {
                    String nombreP = lista.get(i).getAsJsonObject().get("pokemon").getAsJsonObject().get("name").getAsString();
                    modelo.addElement(nombreP);
                }
                listaPokemones.setModel(modelo); // Asignar los nombres a tu JList
                lblNombre.setText("Resultados de tipo: " + entrada);
            }
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró nada con: " + entrada);
        }
        
        response.close();
        httpClient.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

