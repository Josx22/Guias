private void actualizarDetalles(JsonObject obj) throws Exception {
    lblNombre.setText(obj.get("name").getAsString().toUpperCase());
    
    // Stats
    int peso = obj.get("weight").getAsInt();
    int altura = obj.get("height").getAsInt();
    lblStats.setText("<html>Peso: " + peso + " lb<br>Altura: " + altura + " dm</html>");
    
    // Imagen
    String urlImg = obj.getAsJsonObject("sprites").get("front_default").getAsString();
    lblImagen.setIcon(new ImageIcon(ImageIO.read(new URL(urlImg))));
}
